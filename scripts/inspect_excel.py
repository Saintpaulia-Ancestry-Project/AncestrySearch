for k, p in patterns.items():
    m = nz[nz.str.contains(p, flags=re.I, regex=True)]
    rows.append([k, len(m), "; ".join(x[:70] for x in m.drop_duplicates().head(3))])
table(rows, ["pattern", "notes matching", "examples"])
