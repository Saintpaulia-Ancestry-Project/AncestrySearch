# ---------------------------------------------------------------- placeholders & stubs
w("## 6. Parent columns: placeholders\n")
PLACEHOLDER = re.compile(r"^(|\?+|-+|—|–|n/?a|none|unknown|unk|not known|lost|\?.*lost.*|unknown.*|\(.*unknown.*\))$", re.I)
for col in ["Seed Parent", "Pollen Parent"]:
    vc = nm[col].map(clean).value_counts()
    ph = vc[[bool(PLACEHOLDER.match(k)) for k in vc.index]]
    w(f"**{col}** – blank: {int((nm[col].map(clean) == '').sum())}; placeholder-like values:\n")
    table([[repr(k), v] for k, v in ph.items()], ["value", "count"])
# anything else that is clearly not a plant name
w("Other non-plant-looking parent values (generic words, seedlings, 'seeds from', 'open pollinated', etc.):\n")
odd = collections.Counter()
for col in ["Seed Parent", "Pollen Parent"]:
    for v in nm[col].map(clean):
        if v and not PLACEHOLDER.match(v) and re.search(
                r"\bseed(ling)?s?\b|open|poll|species|unnamed|unregistered|mix|various|from|\?|probably|maybe|possibl|unsure|x ", v, re.I):
            odd[v] += 1
table([[repr(k), v] for k, v in odd.most_common(120)], ["value", "count"])
w(f"({len(odd)} distinct values; first 120 shown)\n")

w("## 7. Parents with no plant row (future stubs)\n")
plants = {norm(x) for x in nm["Plant Name"]}
stub = collections.Counter()
for col in ["Seed Parent", "Pollen Parent"]:
    for v in nm[col].map(clean):
        if v and not PLACEHOLDER.match(v) and norm(v) not in plants:
            stub[v] += 1
w(f"Distinct non-placeholder parent values: "
  f"{len({clean(v) for c in ['Seed Parent','Pollen Parent'] for v in nm[c] if clean(v) and not PLACEHOLDER.match(clean(v))})}; "
  f"never appear as a plant name: **{len(stub)}** ({sum(stub.values())} uses).\n")
w("Top 100 by usage:\n")
table([[k, v] for k, v in stub.most_common(100)], ["parent", "uses"])
# stubs that are near-misses of an existing plant
pn = sorted({clean(x) for x in nm["Plant Name"]})
pnorm = {norm(x): x for x in pn}
miss = []
for k in stub:
    m = difflib.get_close_matches(norm(k), list(pnorm), n=1, cutoff=0.9)
    if m:
        miss.append([k, pnorm[m[0]]])
w(f"Stub candidates that are probably misspellings of an existing plant ({len(miss)}):\n")
table(miss[:200], ["parent value", "closest plant name"])

# ---------------------------------------------------------------- notes
