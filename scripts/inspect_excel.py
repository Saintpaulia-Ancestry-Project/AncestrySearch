# ---------------------------------------------------------------- SQLite source
import sqlite3

SQLITE = ROOT / "source" / "AfricanVioletAncestry.sqlite"
if SQLITE.exists():
    con = sqlite3.connect(f"file:{SQLITE}?mode=ro", uri=True)
    v = pd.read_sql("select * from Varieties", con)
    con.close()
    w("## 10. SQLite source (Varieties)\n")
    w(f"{len(v)} rows; {v['Name'].nunique()} distinct names.\n")
    table([[c, int(v[c].notna().sum())] for c in v.columns], ["column", "non-null"])

    def nrm(s):
        return norm(s)

    xl = {nrm(x) for x in nm["Plant Name"]}
    sq = {nrm(x) for x in v["Name"].dropna()}
    w(f"Name overlap with xlsx `Name` sheet: **{len(xl & sq)}** shared; "
      f"{len(sq - xl)} SQLite-only; {len(xl - sq)} xlsx-only.\n")

    dn = v[v["Name"].map(lambda s: nrm(s) if isinstance(s, str) else None).duplicated(keep=False) & v["Name"].notna()]
    w("Duplicate names within SQLite:\n")
    table(dn.sort_values("Name")[["Name", "Sport Parent", "Hybridiser", "AVSA Registration"]].values.tolist(),
          ["name", "sport parent", "hybridiser", "AVSA #"])

    sp = v["Sport Parent"].dropna().map(clean)
    sp_missing = sorted({s for s in sp if nrm(s) not in sq})
    w(f"Sport parents: {sp.nunique()} distinct; not present as a SQLite name: {len(sp_missing)}"
      f" ({sum(1 for s in sp_missing if nrm(s) in xl)} of those exist in xlsx).\n")
    for s in sp_missing:
        w(f"- {s}")
    w()
    in_x = sum(1 for s in set(sp) if nrm(s) in xl)
    w(f"Sport parents also present in xlsx `Name`: {in_x} of {sp.nunique()}.\n")

    # cross-check: xlsx cells saying 'sport of' vs SQLite sport parent
    xs = nm[(nm["Pollen Parent"].map(clean).str.lower() == "sport of")]
    sqmap = {nrm(r.Name): clean(r["Sport Parent"]) for _, r in v.dropna(subset=["Name", "Sport Parent"]).iterrows()}
    agree = disagree = missing = 0
    bad = []
    for _, r in xs.iterrows():
        k = nrm(r["Plant Name"])
        if k not in sqmap:
            missing += 1
        elif nrm(sqmap[k]) == nrm(re.sub(r"\(\s*sport of\s*\)", "", clean(r["Seed Parent"]), flags=re.I)):
            agree += 1
        else:
            disagree += 1
            bad.append([clean(r["Plant Name"]), clean(r["Seed Parent"]), sqmap[k]])
    w(f"xlsx rows with Pollen Parent = 'sport of': {len(xs)} -> SQLite agrees on parent: {agree}, "
      f"disagrees: {disagree}, plant not in SQLite sport list: {missing}.\n")
    table(bad[:100], ["cultivar", "xlsx seed parent", "SQLite sport parent"])

    reg = v["AVSA Registration"].dropna()
    rd = v[v["AVSA Registration"].isin(reg[reg.duplicated()])]
    w("Repeated AVSA registration numbers:\n")
    table(rd.sort_values("AVSA Registration")[["AVSA Registration", "Name", "Date registered"]].values.tolist(),
          ["AVSA #", "name", "date"])
    badd = v["Date registered"].dropna()
    badd = badd[pd.to_datetime(badd, format="%m/%d/%Y", errors="coerce").isna()]
    w(f"Registration dates not parseable as m/d/yyyy: {len(badd)} {list(badd.head(10))}\n")

    hs = v["Hybridiser"].dropna().map(clean)
    xh = {clean(x) for x in nm["Hybridizer"] if clean(x)}

    def surname_init(s):
        m = re.match(r"^([^,]+),\s*(\w)", s)
        return (norm(m.group(1)), m.group(2).lower()) if m else None

    xi = collections.defaultdict(set)
    for h in xh:
        k = surname_init(h)
        if k:
            xi[k].add(h)
    unm, amb, ok = [], [], 0
    for h in sorted(set(hs)):
        k = surname_init(h)
        c = xi.get(k, set()) if k else set()
        if len(c) == 1:
            ok += 1
        elif len(c) > 1:
            amb.append([h, "; ".join(sorted(c))])
        else:
            unm.append(h)
    w(f"SQLite hybridiser values: {len(set(hs))} distinct. Map uniquely to an xlsx hybridizer by "
      f"surname+initial: {ok}; ambiguous: {len(amb)}; no match: {len(unm)}.\n")
    table(amb, ["SQLite", "xlsx candidates"])
    w("No xlsx match (first 60): " + "; ".join(unm[:60]) + "\n")
    w("Size classes: " + ", ".join(f"{k} ({n})" for k, n in v["Variety"].value_counts().items()) + "\n")

OUT.parent.mkdir(exist_ok=True)
OUT.write_text("\n".join(out), encoding="utf-8")
print(f"Wrote {OUT} ({len(out)} lines)")
