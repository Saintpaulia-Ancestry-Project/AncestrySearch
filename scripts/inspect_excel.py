def near_dupes(values, cutoff=0.93, label=""):
    vals = sorted({clean(v) for v in values if clean(v)})
    by_norm = collections.defaultdict(list)
    for v in vals:
        by_norm[norm(v)].append(v)
    res = [(" ≙ ".join(g), "same after case/punctuation") for g in by_norm.values() if len(g) > 1]
    keys_ = sorted(by_norm)
    # compare within first-letter buckets and similar length to keep this fast
    buckets = collections.defaultdict(list)
    for k in keys_:
        buckets[k[:2]].append(k)
    for b in buckets.values():
        for i, a in enumerate(b):
            for c in b[i + 1:]:
                if abs(len(a) - len(c)) <= 2 and len(a) > 5 and difflib.SequenceMatcher(None, a, c).ratio() >= cutoff:
                    res.append((f"{by_norm[a][0]} ~ {by_norm[c][0]}", "fuzzy"))
    return res


