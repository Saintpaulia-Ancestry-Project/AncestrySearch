w("## 3. Comparison of the four sheets\n")
keys = {n: collections.Counter(tuple(clean(x) for x in r) for r in df[DATA].values) for n, df in d.items()}
base = keys["Name"]
rows = []
for n in SHEETS[1:]:
    rows.append([n, sum((base - keys[n]).values()), sum((keys[n] - base).values())])
table(rows, ["sheet vs Name", "rows only in Name", "rows only in this sheet"])

tsk = {}
for n, df in d.items():
    c = collections.Counter()
    for _, r in df.iterrows():
        if str(r["Timestamp"]).strip():
            c[(tuple(clean(x) for x in r[DATA].values[:4]), str(to_ts(r["Timestamp"])))] += 1
    tsk[n] = c
w("Timestamp comparison (timestamps are real datetimes in `Name` but bare serial floats in the others; "
  "converted before comparing):\n")
table([[n, sum(tsk[n].values()), sum((tsk["Name"] - tsk[n]).values()), sum((tsk[n] - tsk["Name"]).values())]
       for n in SHEETS], ["sheet", "timestamped rows", "missing vs Name", "extra vs Name"])

nm = d["Name"]
dup = nm[nm.duplicated(subset=DATA, keep=False)]
w(f"Exact duplicate records within the data (same name, parents, hybridizer, notes): "
  f"**{len(dup) - dup.drop_duplicates(subset=DATA).shape[0]} surplus rows** "
  f"across {dup.drop_duplicates(subset=DATA).shape[0]} records.\n")
table([[k, v] for k, v in dup["Plant Name"].map(clean).value_counts().items()], ["plant name", "copies"])
names_counts = nm["Plant Name"].map(clean).value_counts()
conflict = [k for k, v in names_counts.items() if v > 1 and nm[nm["Plant Name"].map(clean) == k][DATA].map(clean).drop_duplicates().shape[0] > 1]
w(f"Names that repeat with *differing* parents/hybridizer/notes: {len(conflict)}\n")
for k in conflict[:40]:
    sub = nm[nm["Plant Name"].map(clean) == k][DATA].map(clean).drop_duplicates()
    w(f"- **{k}**: " + " / ".join(" · ".join(r[1:4]) for r in sub.values))
